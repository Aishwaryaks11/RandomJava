package WrapperClass;

public class UnBoxing {

	public static void main(String[] args) {
    Integer i=67;
    int a=i;
    System.out.println(a+" "+i);
    System.out.println("------------------");
    Double d=68.54;
    double b=d;
    System.out.println(b+" "+d);
    System.out.println("-----------------------------");
    Character ch='h';
    char c=ch;
    System.out.println(c+" "+ch);
	}

}
