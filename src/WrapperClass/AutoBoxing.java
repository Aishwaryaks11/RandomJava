package WrapperClass;

public class AutoBoxing {

	public static void main(String[] args) {
    int a=25;
    Integer i=a;
    System.out.println(a+" "+i);
    System.out.println("------------------");
    double b=23.76;
    Double d=b;
    System.out.println(b+" "+d);
    System.out.println("-----------------------------");
    char c='n';
    Character ch=c;
    System.out.println(c+" "+ch);
	}

}
